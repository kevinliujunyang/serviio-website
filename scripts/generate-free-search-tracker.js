const headers = [
  'priority',
  'channel',
  'target',
  'url',
  'status',
  'owner',
  'date_submitted',
  'date_live',
  'landing_url',
  'utm_url',
  'anchor_or_listing_phrase',
  'notes',
];

function absoluteUrl(path) {
  return `https://serviio.ai${path}`;
}

function utmUrl(row) {
  const url = new URL(absoluteUrl(row.landingPath));
  url.searchParams.set('utm_source', row.source);
  url.searchParams.set('utm_medium', row.medium);
  url.searchParams.set('utm_campaign', 'free_search_marketing');
  return url.toString();
}

function csvEscape(value) {
  const stringValue = String(value ?? '');
  if (/[",\n]/.test(stringValue)) {
    return `"${stringValue.replace(/"/g, '""')}"`;
  }
  return stringValue;
}

const csv = [
  headers.join(','),
  ...rows.map((row) => [
    row.priority,
    row.channel,
    row.target,
    row.url,
    row.status,
    row.owner,
    row.dateSubmitted,
    row.dateLive,
    absoluteUrl(row.landingPath),
    utmUrl(row),
    row.anchor,
    row.notes,
  ].map(csvEscape).join(',')),
].join('\n');

